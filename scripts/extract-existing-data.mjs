import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const root = process.cwd();
const sourcePath = path.join(root, "日暮途远.html");
const html = fs.readFileSync(sourcePath, "utf8");
const dataMatch = html.match(/<!-- DATA -->([\s\S]*?)<!-- APP -->/);

if (!dataMatch) {
  throw new Error("Could not find DATA block in 日暮途远.html");
}

const dataScript = dataMatch[1].replace(/<\/?script>/g, "");
const sandbox = { window: {} };
vm.runInNewContext(dataScript, sandbox, { filename: "日暮途远.html" });

const { SITE, PROJECTS, COLLECTIONS, NOVELS, ESSAYS, BITS } = sandbox.window;

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function emptyDir(dir) {
  fs.rmSync(dir, { recursive: true, force: true });
  ensureDir(dir);
}

function toKebab(input, fallback) {
  const ascii = String(input)
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return ascii || fallback;
}

function frontmatter(data) {
  return `---\n${Object.entries(data)
    .map(([key, value]) => `${key}: ${JSON.stringify(value)}`)
    .join("\n")}\n---\n\n`;
}

function proseToMarkdown(paragraphs) {
  return paragraphs
    .map((paragraph) => String(paragraph).trim())
    .filter(Boolean)
    .join("\n\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd() + "\n";
}

function writeMarkdown(filePath, meta, body) {
  fs.writeFileSync(filePath, frontmatter(meta) + proseToMarkdown(body), "utf8");
}

const contentRoot = path.join(root, "src", "content");
const dataRoot = path.join(root, "src", "data");

for (const dir of ["collections", "novels", "essays", "bits"]) {
  emptyDir(path.join(contentRoot, dir));
}
ensureDir(dataRoot);

const collectionMeta = COLLECTIONS.map((collection, collectionIndex) => {
  const collectionDir = path.join(contentRoot, "collections", collection.id);
  ensureDir(collectionDir);

  collection.pieces.forEach((piece, pieceIndex) => {
    writeMarkdown(
      path.join(collectionDir, `${piece.id}.md`),
      {
        title: piece.title,
        sub: piece.sub || "",
        date: piece.date || "",
        reading: piece.reading || "",
        collection: collection.id,
        order: pieceIndex,
      },
      piece.body || [],
    );

    if (piece.appendix) {
      writeMarkdown(
        path.join(collectionDir, `${piece.id}-appendix.md`),
        {
          title: piece.appendix.title,
          sub: "",
          date: piece.date || "",
          reading: "",
          collection: collection.id,
          parent: piece.id,
          order: pieceIndex,
          appendix: true,
        },
        piece.appendix.body || [],
      );
    }
  });

  return {
    id: collection.id,
    name: collection.name,
    dedication: collection.dedication || "",
    note: collection.note || "",
    order: collectionIndex,
    preface: collection.preface || null,
    prefaceOld: collection.preface_old || null,
  };
});

const novelMeta = NOVELS.map((novel, novelIndex) => {
  const novelDir = path.join(contentRoot, "novels", novel.id);
  ensureDir(novelDir);

  const chapters = novel.chapters.map((chapter, chapterIndex) => {
    const slug = `${String(chapterIndex).padStart(2, "0")}-${toKebab(chapter.title, `chapter-${chapterIndex}`)}`;
    writeMarkdown(
      path.join(novelDir, `${slug}.md`),
      {
        title: chapter.title,
        novel: novel.id,
        order: chapterIndex,
      },
      chapter.body || [],
    );
    return {
      slug,
      title: chapter.title,
      order: chapterIndex,
    };
  });

  return {
    id: novel.id,
    title: novel.title,
    subtitle: novel.subtitle || "",
    status: novel.status || "",
    date: novel.date || "",
    synopsis: novel.synopsis || "",
    order: novelIndex,
    chapters,
  };
});

ESSAYS.forEach((essay, index) => {
  writeMarkdown(
    path.join(contentRoot, "essays", `${essay.id}.md`),
    {
      title: essay.title,
      sub: essay.sub || "",
      date: essay.date || "",
      reading: essay.reading || "",
      order: index,
    },
    essay.body || [],
  );
});

BITS.forEach((bit, index) => {
  writeMarkdown(
    path.join(contentRoot, "bits", `${bit.id}.md`),
    {
      title: bit.title,
      sub: bit.sub || "",
      date: bit.date || "",
      reading: bit.reading || "",
      order: index,
    },
    bit.body || [],
  );
});

const generated = `// Generated by scripts/extract-existing-data.mjs from 日暮途远.html.
// Re-run the script when the legacy single-file HTML is the source of truth.

export const site = ${JSON.stringify(SITE, null, 2)} as const;

export const projects = ${JSON.stringify(PROJECTS, null, 2)} as const;

export const collections = ${JSON.stringify(collectionMeta, null, 2)} as const;

export const novels = ${JSON.stringify(novelMeta, null, 2)} as const;
`;

fs.writeFileSync(path.join(dataRoot, "generated.ts"), generated, "utf8");

console.log("Extracted site data into src/data/generated.ts and src/content.");
